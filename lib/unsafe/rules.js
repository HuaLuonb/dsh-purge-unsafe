export const MODEL_PRESETS = {
  generic: GENERIC,
  qwen: QWEN,
  glm: GLM,
  deepseek: DEEPSEEK,
};

export function rulesFor(model) {
  const id = String(model ?? '').trim().toLowerCase();
  if (!id) return MODEL_PRESETS.generic;
  if (id.includes('qwen')) return MODEL_PRESETS.qwen;
  if (id.includes('glm')) return MODEL_PRESETS.glm;
  if (id.includes('deepseek')) return MODEL_PRESETS.deepseek;
  return MODEL_PRESETS.generic;
}
